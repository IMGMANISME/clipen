"""Maintainer-only signing of reviewed system Skill releases; never a UI API."""

import argparse
import base64
import hashlib
from pathlib import Path
import stat
import sys
import tempfile

from tools.skill_guard import PROJECT_ROOT, SkillError, _atomic_write, _directory, _inventory, _openssl, _root, _verify_signature
import json


def sign_release(private_key: Path, root: Path = PROJECT_ROOT) -> None:
    key = private_key.resolve(strict=True)
    if key.is_relative_to(root.resolve()) or private_key.is_symlink():
        raise SkillError("Keep the private signing key outside the repository, without symlinks.")
    info = key.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_mode & 0o077:
        raise SkillError("Private signing key must be a regular, owner-only file.")
    der = _openssl("pkey", "-in", str(key), "-pubout", "-outform", "DER")
    if len(der) != 44 or not der.startswith(bytes.fromhex("302a300506032b6570032100")):
        raise SkillError("Only Ed25519 signing keys are supported.")
    public_key = _openssl("pkey", "-in", str(key), "-pubout")
    contents = _inventory(root)
    if "clipen-core" not in contents:
        raise SkillError("A release must include clipen-core.")
    entries = {}
    for name, data in contents.items():
        if not data.decode("utf-8").strip():
            raise SkillError("Cannot release an empty Skill.")
        entries[name] = {"role": "core" if name == "clipen-core" else "editing",
                         "sha256": hashlib.sha256(data).hexdigest(), "size": len(data)}
    data = (json.dumps({"format": 1, "skills": entries}, sort_keys=True, indent=2) + "\n").encode()
    with tempfile.TemporaryDirectory(prefix="clipen-sign-") as temporary:
        manifest = Path(temporary) / "manifest.json"
        manifest.write_bytes(data)
        signature = _openssl("pkeyutl", "-sign", "-inkey", str(key), "-rawin", "-in", str(manifest))
    _verify_signature(data, signature, public_key)
    trust = (
        '# Public verification material only; generated by tools.sign_skills.\n'
        '# This file and the verifier form the trusted application code.\n'
        f'PUBLIC_KEY_PEM = {public_key!r}\n'
        f'MANIFEST_SHA256 = "{hashlib.sha256(data).hexdigest()}"\n'
    ).encode()
    with _root(root) as repo, _directory(repo, "skills") as skills, _directory(repo, "tools") as tools:
        # Last write is the pinned trust data. Partial releases fail closed.
        _atomic_write(skills, "system-manifest.json", data)
        _atomic_write(skills, "system-manifest.sig", base64.b64encode(signature) + b"\n")
        _atomic_write(tools, "skill_trust.py", trust)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--private-key", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        sign_release(args.private_key)
    except (SkillError, OSError, UnicodeError) as error:
        print(f"Release refused: {error}", file=sys.stderr)
        return 1
    print("Signed the reviewed system bundle; only public verification material was written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
